    public function soon(string $page): string
    {
        $info = self::PAGES[$page] ?? null;
        if ($info === null) {
            $this->notFound();
        }

        return $this->view('pages/soon', [
            'title'  => $info['title'],
            'page'   => $info,
            'robots' => 'noindex, follow',
        ]);
    }

    /** Адреса разделов-заглушек — для routes.php. */
    public static function slugs(): array
    {
        return array_keys(self::PAGES);
    }
